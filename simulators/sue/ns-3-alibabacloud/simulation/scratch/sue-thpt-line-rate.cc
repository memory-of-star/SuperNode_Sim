/*
 * S5c GPU-to-GPU throughput measurement (DESIGN §6.12/§9): two hosts behind one
 * switch, full LLR+CBFC lossless, host0 pushes a THPT_GBITS payload to host1 at
 * ~line-rate pacing, and we report the achieved transfer rate (Gbps) plus the
 * lossless counters. Run once with THPT_LOSS_EVERY=0 (clean link) and again with
 * THPT_LOSS_EVERY=N (deterministic 1/N frame loss on the host0->switch link via
 * SueErrorModel::SetBadEvery) to quantify the throughput cost of loss / LLR
 * NACK-replay recovery.
 *
 * Pacing: the sender (SueLiteEndpoint) self-chains at interval = 0.95 * (wire
 * cycle of one frame) by default, i.e. offered load slightly above line rate, so
 * the measured rate is what the CBFC credit window + LLR window actually sustain,
 * not what the sender happens to offer. (A 0.95 factor keeps the egress backlog
 * small; the measured rate uses delivered bytes / transfer duration, which is
 * independent of the offered load once the link is saturated.)
 *
 * Control-plane model (post decoupling, DESIGN §12.26 + THU alignment §12.37):
 * the device CtlOS wire gate is a FIXED 400B floor (UEC §5.2.11.2, 2%-of-
 * bandwidth cap), INDEPENDENT of the LLR ACK period: ApplySueConfig fixes the
 * gate at 400B and drives the ACK cadence separately from
 * LLR_CTLOS_TARGET_SPACING (2048B -> 40.96ns at 400G). CF_Update is lowest
 * priority (plain FIFO behind ACK/NACK, UEC Table 5-12), generated by the
 * data-quantity threshold (2075B, THU default-aligned; CF_MIN=0) plus the
 * CF_max periodic full update. The credit window (THPT_CREDITS) is thus only
 * required to cover the threshold + one frame (~4.1KB = CL 32 @256B), not
 * the whole transfer — the pre-alignment binding (512 credits @ 91.75%) is
 * gone with per-2KB refunds.
 *
 * LLR replay (UEC §5.1.4): the replay timer is the ACK-timeout detector (armed
 * on frame TX, RESET whenever an ACK releases buffered frames per rule 4,
 * expires only on genuine ACK silence -> REPLAY). It is auto-sized to ~10x the
 * link's LLR RTT (THPT_REPLAY_NS=0) so it stays a lost-ACK/NACK safety net at
 * any rate; a fixed 50µs tuned for 400G is ~= the ACK RTT at 1G and replays
 * 84% of frames, capping 1G at 0.76 Gbps. Data-age is raised to its max (4s)
 * so only a genuinely broken link triggers FLUSH.
 *
 * Env knobs:
 *   THPT_RATE         link rate string ("400Gbps")  THPT_GBITS   payload (default 10)
 *   THPT_PAYLOAD      frame payload bytes (2048)    THPT_INTERVAL_NS  0=auto(0.95×wire)
 *   THPT_LOSS_EVERY   0=none; N=SetBadEvery(N) (1/N bad)  THPT_THREADS  1
 *   THPT_LLR          LLR 使能(默认 1;0 = 无 LLR 链路:conf LLR_MODE 0 +
 *                     收端设备 SetLlrEnabled(true) 走 legacy 只丢 BAD 分支——
 *                     同样 1/N 坏帧注入下直接丢帧,与 LLR 无损恢复对比)
 *   THPT_CREDITS      CBFC credit limit per VC (default 1024; binding only below
 *   THPT_CREDIT_SIZE  CBFC credit size in B (default 256; window bytes = limit x size)
 *                     CL 32 @256B under the THU-aligned refund — deadlock below
 *                     one frame (CL 8), degraded at one frame (CL 16), line rate
 *                     from CL 32; run-s5c-thpt.sh passes 1024)
 *   THPT_CFMIN        CBFC CF_min_timer in wire bytes (default 0 = THU 对齐预设:
 *                     threshold 2075 主导、无引擎地板;设备 400B 门封顶,§12.37)
 *   THPT_REPLAY_NS    LLR replay_timer_max override (0 = auto: 10x LLR RTT)
 *   THPT_PROP_NS      link propagation one-way (default 0; drives the CF refund
 *                     RTT — line-rate regime converges as W/(W + RTT x rate))
 *   THPT_CF_THRESHOLD CF data-quantity threshold in B (default 2075 = THU
 *                     aligned preset; the jump window = threshold + frame)
 *   THPT_FWD_NS       switch forward budget ns (default 0; defers the CF refund
 *                     into the egress path — congestion service time enters
 *                     the refund RTT and throttles the sender)
 */
