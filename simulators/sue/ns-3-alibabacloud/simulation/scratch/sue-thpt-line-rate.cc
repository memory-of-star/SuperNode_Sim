static bool g_ok = true;
#define CHECK(c, m) do { bool _c=(c); std::cout<<"  ["<<(_c?"ok":"FAIL")<<"] "<<m<<"\n"; g_ok=g_ok&&_c; } while(0)

// host1 receive observer: counts payload frames/bytes and records first/last
// arrival timestamps (exact transfer window). The upcall packet still carries
// the SueHeader (the device strips only the LLR preamble), so count payload
// bytes = GetSize() minus the SueHeader — the CHECK compares against
// frames*payload and the reported rate is the useful payload rate, not the
// wire bytes moved (which would include the 14B header per frame).
static std::atomic<uint64_t> g_rxFrames{0}, g_rxBytes{0};
static uint64_t g_firstRxNs = 0, g_lastRxNs = 0;
static void RxObs (Ptr<SueNetDevice>, Ptr<Packet> p, SueHeader h)
{
  ++g_rxFrames;
  g_rxBytes += p->GetSize () - h.GetSerializedSize ();
  const uint64_t now = Simulator::Now ().GetNanoSeconds ();
  if (g_rxFrames == 1) { g_firstRxNs = now; }
  g_lastRxNs = now;
}

// Debug sampler: prints the delivered frame count at several sim times, so the
// stall point (if any) is visible instead of a silent final counter.
static void Sample (const char *label)
{
  std::cout << "    t=" << Simulator::Now ().GetNanoSeconds () << "ns rx_frames=" << g_rxFrames.load ()
            << " bytes=" << g_rxBytes.load () << "  (" << label << ")\n";
}

// Credit/LLR-state probe: prints per-device CBFC credit (CC / CU / R_VC_CF) and
// LLR rx counters at a sim time, so the exact stall mechanism (wrapped CU vs
// stale CF vs LLR window) is visible instead of inferred from final counters.
static void Probe (const char *label)
{
  std::cout << "  PROBE t=" << Simulator::Now ().GetNanoSeconds () << "ns (" << label << ")\n";
  for (uint32_t n = 0; n < SueGetNNodes (); ++n)
    {
      Ptr<Node> node = SueGetDevice (n, 0)->GetNode ();
      for (uint32_t d = 0; d < node->GetNDevices (); ++d)
        {
          Ptr<SueNetDevice> dev = DynamicCast<SueNetDevice> (node->GetDevice (d));
          if (!dev) { continue; }
          std::cout << "    dev[" << n << "][" << d << "]";
          if (dev->GetCbfcEngine ())
            {
              std::cout << " CC=" << dev->GetCbfcEngine ()->GetSvcCc (0)
                        << " CU=" << dev->GetCbfcEngine ()->GetSvcCu (0)
                        << " R_CF=" << dev->GetCbfcEngine ()->GetRvcCf (0);
            }
          if (dev->GetLlrEngine ())
            {
              const SueLlrCounters &c = dev->GetLlrEngine ()->GetCounters ();
              std::cout << " tx_state=" << (int) dev->GetLlrEngine ()->GetTxState ()
                        << " replayed=" << dev->GetLlrEngine ()->GetReplaySize ()
                        << " out=" << dev->GetLlrEngine ()->GetOutstandingSeq ()
                        << " rx_dup=" << c.rx_duplicate_seq << " rx_miss=" << c.rx_missing_seq
                        << " rx_replay=" << c.rx_replay << " rx_ok=" << c.rx_ok
                        << " nack_tx=" << c.tx_nack_ctl_os << " nack_rx=" << c.rx_nack_ctl_os
                        << " ack_rx=" << c.rx_ack_ctl_os
                        << " acked=" << dev->GetLlrEngine ()->GetAckedSeq ()
                        << " nxtRx=" << dev->GetLlrEngine ()->GetNextRxSeq ();
            }
          std::cout << "\n";
        }
    }
}

int
main ()
{
  // ---- env knobs ----
  std::string rateStr = "400Gbps";
  if (const char *e = std::getenv ("THPT_RATE")) { rateStr = e; }
  uint32_t gbits = 10;
  if (const char *e = std::getenv ("THPT_GBITS")) { gbits = std::atoi (e); }
  if (gbits == 0) { gbits = 10; }
  uint32_t payload = 2048;
  if (const char *e = std::getenv ("THPT_PAYLOAD")) { payload = std::atoi (e); }
  if (payload == 0) { payload = 2048; }
  int64_t intervalNs = 0;
  if (const char *e = std::getenv ("THPT_INTERVAL_NS")) { intervalNs = std::atoi (e); }
  uint32_t lossEvery = 0;
  if (const char *e = std::getenv ("THPT_LOSS_EVERY")) { lossEvery = std::atoi (e); }
  uint32_t llrEna = 1;
  if (const char *e = std::getenv ("THPT_LLR")) { llrEna = std::atoi (e) == 1 ? 1 : 0; }
  uint32_t threads = 1;
  if (const char *e = std::getenv ("THPT_THREADS")) { threads = std::atoi (e); }
  if (threads == 0) { threads = 1; }
  uint32_t creditLimit = 1024;
  if (const char *e = std::getenv ("THPT_CREDITS")) { creditLimit = std::atoi (e); }
  if (creditLimit == 0) { creditLimit = 1024; }
  // CBFC credit size (B) — the sender window in BYTES is creditLimit x
  // creditSize, so the window-bound transition of the rate curve scales with
  // this knob (credits-vs-rate 扫描矩阵;默认 256 = 预置值,零回归)。
  uint32_t creditSize = 256;
  if (const char *e = std::getenv ("THPT_CREDIT_SIZE")) { creditSize = std::atoi (e); }
  if (creditSize == 0) { creditSize = 256; }
  // THU 对齐预设:CF_MIN=0 + threshold 2075 -> 阈值即时发送(THU 默认档)。
  uint32_t cfMin = 0;
  if (const char *e = std::getenv ("THPT_CFMIN")) { cfMin = std::atoi (e); }
  // LLR replay timer override (ns). 0 = auto: derived below from the link rate
  // per UEC §5.1.4 ("the replay_timer should count ~10x the expected LLR round
  // trip time"). With the rule-4 reset (ACK releasing buffered frames restarts
  // the timer) the timer only expires on genuine ACK silence, so it is a
  // lost-ACK/NACK safety net and must scale with the link's RTT, not be a fixed
  // 50µs tuned for 400G.
  uint32_t replayNs = 0;
  if (const char *e = std::getenv ("THPT_REPLAY_NS")) { replayNs = std::atoi (e); }
  uint32_t propNs = 0;
  if (const char *e = std::getenv ("THPT_PROP_NS")) { propNs = std::atoi (e); }
  uint32_t cfThreshold = 2075;
  if (const char *e = std::getenv ("THPT_CF_THRESHOLD")) { cfThreshold = std::atoi (e); }
  uint32_t fwdNs = 0;
  if (const char *e = std::getenv ("THPT_FWD_NS")) { fwdNs = std::atoi (e); }

  const DataRate rate (rateStr);
  const double bps = rate.GetBitRate ();

  // Per-frame wire cycle: SueHeader(14B, no vlan/shim) + payload + LLR preamble
  // (8B, on the wire) + IFG (12B). Endpoint offered interval = 0.95 × this.
  const Time dataWire = rate.CalculateBytesTxTime (14 + payload + 8);
  const Time ifgWire = rate.CalculateBytesTxTime (12);
  const Time wireCycle = dataWire + ifgWire;
  if (intervalNs == 0) { intervalNs = wireCycle.GetNanoSeconds () * 95 / 100; }
  // LLR ACK cadence (LLR_CTLOS_TARGET_SPACING 2048B -> time at this link rate).
  const Time ackPeriod = rate.CalculateBytesTxTime (2048);
  // UEC §5.1.4: replay_timer_max ~ 10x expected LLR RTT. Estimate RTT as two
  // wire cycles (host0->sw->host1, store-and-forward) + two 1µs prop hops +
  // one ackPeriod grid wait for the cumulative ACK. Auto when THPT_REPLAY_NS=0.
  if (replayNs == 0)
    {
      const Time rtt = 2 * wireCycle + 2 * MicroSeconds (1) + ackPeriod;
      replayNs = 10 * rtt.GetNanoSeconds ();
    }

  const uint64_t targetBytes = (uint64_t) gbits * 1000000000ULL / 8ULL;
  const uint64_t frames = (targetBytes + payload - 1) / payload;
  const double transferUs = (gbits * 1.0e9) / bps * 1.0e6;   // offered transfer length (µs)

  std::cout << "THPT rate=" << rateStr << " payload=" << payload << "B"
            << " frames=" << frames << " (" << gbits << " Gbit)"
            << " interval=" << intervalNs << "ns (wire cycle " << wireCycle.GetNanoSeconds () << "ns)"
            << " loss=" << (lossEvery ? "1/" + std::to_string (lossEvery) : "none")
            << " threads=" << threads << "\n";

  // ---- topo: host0 -- switch2 -- host1, all LLR+CBFC ----
  const std::string topo = "/tmp/sue-s5c-thpt-topo.txt";
  const std::string conf = "/tmp/sue-s5c-thpt.conf";
  std::ofstream (topo) << "type=SUE\n"
                       << "nodes 3\n"
                       << "switch 2\n"
                       << "link 0 2 " << rateStr << " " << llrEna << " CBFC 0\n"
                       << "link 1 2 " << rateStr << " " << llrEna << " CBFC 0\n";
  // 400Gbps preset (conf/sue-400g.conf) mirrored inline, EXCEPT
  // LLR_CTLOS_TARGET_SPACING kept at 2048B (the 400G preset uses 2050B for the
  // NS-grid fit, §12.37) — this program's line-rate analysis is derived for
  // 2048B. Data-age is set to its max (4s) so a slow CBFC refund (return CtlOS
  // ACK-saturated) never spuriously FLUSHes the replay buffer — only a
  // genuinely broken link would discard. The credit window (THPT_CREDITS) is
  // tunable for the line-rate-window analysis.
  std::ofstream (conf) << "ENABLE_SCALEUP 1\n"
                       << "ENABLE_SCALEUP_WORKLOAD 0\n"
                       << "SUE_MTP_THREADS " << threads << "\n"
                       << "SUE_ETH_TYPE_0 0xFCF1\n"
                       << "SUE_ETH_TYPE_0_HAS_SHIM 0\n"
                       << "SUE_ETH_TYPE_1 0xFCF2\n"
                       << "SUE_ETH_TYPE_1_HAS_SHIM 1\n"
                       << "SUE_IFG_BYTES 12\n"
                       << "SUE_LINK_PROPAGATION_NS " << propNs << "\n"
                       << "SUE_SWITCH_FWD_BUDGET_NS " << fwdNs << "\n"
                       << "LLR_MODE_LOCAL " << llrEna << "\n"
                       << "LLR_MODE_REMOTE " << llrEna << "\n"
                       << "LLR_INIT_BEHAVIOR BLOCK\n"
                       << "LLR_FLUSH_BEHAVIOR BLOCK\n"
                       << "LLR_RE_INIT_ON_DISCARD 1\n"
                       << "LLR_OUTSTANDING_SEQ_MAX 65536\n"
                       << "LLR_OUTSTANDING_DATA_MAX 1048576\n"
                       << "LLR_REPLAY_BUF_MAX 1048576\n"
                       << "LLR_REPLAY_TIMER_MAX_NS " << replayNs << "\n"
                       << "LLR_REPLAY_CT_MAX 5\n"
                       << "LLR_INIT_TIMER_MAX_NS 50000\n"
                       << "LLR_INIT_RETRY_MAX 3\n"
                       << "LLR_DATA_AGE_TIMER_MAX_NS 4000000000\n"
                       << "LLR_CTLOS_TARGET_SPACING 2048\n"
                       << "LLR_PCS_LOST_STATUS_TIMER_MAX_NS 0\n"
                       << "FC_MODE CBFC\n"
                       << "CBFC_CREDIT_SIZE " << creditSize << "\n"
                       << "CBFC_VC_CREDIT_LIMIT 0:" << creditLimit << ",1:" << creditLimit
                       << ",2:" << creditLimit << ",3:" << creditLimit << ",4:" << creditLimit
                       << ",5:" << creditLimit << ",6:" << creditLimit << ",7:" << creditLimit << "\n"
                       << "CBFC_CC_MSG_TIMER_US 102\n"
                       << "CBFC_CF_THRESHOLD_BYTES " << cfThreshold << "\n"
                       << "CBFC_CF_MIN_TIMER_BYTES " << cfMin << "\n"
                       << "CBFC_CF_MAX_TIMER_BYTES 1250000\n";

  SueReadConf (conf);
  SueEntryDispatch (topo, conf, nullptr);
  CHECK (SueGetNNodes () == 3, "3 nodes built (got " << SueGetNNodes () << ")");

  // ---- sender: SueLiteEndpoint on host0 (xpu0 -> xpu1), paced ~line rate ----
  Ptr<SueLiteEndpoint> ep0 = CreateObject<SueLiteEndpoint> ();
  ep0->SetSourceXpu (0);
  ep0->SetDevice (SueGetDevice (0, 0));
  ep0->SetDestinationXpu (1);
  ep0->SetPayloadSize (payload);
  ep0->SetFrameCount ((uint32_t) frames);
  ep0->SetInterval (NanoSeconds (intervalNs));
  ep0->SetStartTime (MicroSeconds (100));
  ep0->Start ();

  // ---- receiver: host1 counting upcall (replaces module default) ----
  SueGetDevice (1, 0)->SetReceiveUpcall (MakeCallback (&RxObs));

  // ---- deterministic 1/N frame loss on the host0->switch link ----
  if (lossEvery > 0)
    {
      Ptr<SueErrorModel> em = CreateObject<SueErrorModel> ();
      em->SetBadEvery (lossEvery);
      SueGetDevice (2, 0)->SetErrorModel (em);
      std::cout << "  corruptor: switch(2,0) ingress SetBadEvery(" << lossEvery << ")\n";
    }

  // THPT_LLR=0:topo llrEna=0(无引擎、无 INIT 握手);对全部设备开 legacy
  // 分支(§6.1:"engine absent, llr_enabled flag set: strip preamble, drop BAD
  // frames only")——TX 补 ineligible 前导、RX 剥前导并只丢 BAD,等价"纯丢包
  // 链路"语义:同样 1/N 坏帧注入直接丢弃、无重传恢复。必须在 Run 之前执行。
  if (!llrEna)
    {
      for (uint32_t n = 0; n < 3; ++n)
        {
          for (uint32_t d = 0; d < SueGetDevice (n, 0)->GetNode ()->GetNDevices (); ++d)
            {
              Ptr<SueNetDevice> dev = SueGetDevice (n, d);
              if (dev) { dev->SetLlrEnabled (true); }
            }
        }
    }

  const Time stop = MicroSeconds (100) + MicroSeconds ((uint64_t) (transferUs * 2 + 20000));
  // samplers to visualize the delivery curve
  uint64_t tU[] = { 200, 300, 400, 500, 600, 800, 1000, 2000, 5000, 10000, 30000 };
  for (uint64_t t : tU) { if (MicroSeconds (t) < stop) { Simulator::Schedule (MicroSeconds (t), &Sample, "sample"); } }
  uint64_t pU[] = { 300, 450, 500, 550, 700, 1200 };
  for (uint64_t t : pU) { if (MicroSeconds (t) < stop) { Simulator::Schedule (MicroSeconds (t), &Probe, "probe"); } }
  // Fine-grained credit trace: every 2µs print host0 CC/CU and switch-ingress
  // R_CF so the refund arrival cadence (CU drops) and TX burst cadence (CC
  // jumps) are visible instead of inferred from the final rate.
  for (uint64_t t = 110; t <= 260; t += 2)
    {
      Simulator::Schedule (MicroSeconds (t), [&] {
        Ptr<SueNetDevice> h0 = SueGetDevice (0, 0);
        Ptr<SueNetDevice> sw = SueGetDevice (2, 0);
        std::cout << "    F t=" << Simulator::Now ().GetNanoSeconds () << " h0.CC=" << h0->GetCbfcEngine ()->GetSvcCc (0)
                  << " h0.CU=" << h0->GetCbfcEngine ()->GetSvcCu (0)
                  << " sw.R_CF=" << sw->GetCbfcEngine ()->GetRvcCf (0) << "\n";
      });
    }
  Simulator::Stop (stop);
  auto t0 = std::chrono::steady_clock::now ();
  Simulator::Run ();
  const double wall = std::chrono::duration<double, std::milli> (std::chrono::steady_clock::now () - t0).count ();

  // ---- results ----
  // CheckFcs 从 m_count=1 起算(count%N==0 为坏),故坏帧数 = ⌊sent/N⌋。
  const uint64_t expLost = (!llrEna && lossEvery > 0) ? frames / lossEvery : 0;
  const uint64_t expectedBytes = (frames - expLost) * payload;
  // THPT_LLR=0:topo llrEna=0(无引擎、无 INIT 握手);对全部设备开 legacy
  // 分支(§6.1 注释:"engine absent, llr_enabled flag set: strip preamble,
  // drop BAD frames only")——TX 补 ineligible 前导、RX 剥前导并只丢 BAD,
  // 等价"纯丢包链路"语义:同样 1/N 坏帧注入直接丢弃、无重传恢复。
  const uint64_t sent = ep0->GetTxCount ();
  const uint64_t recv = g_rxFrames.load ();
  const uint64_t bytes = g_rxBytes.load ();
  const uint64_t durNs = (g_lastRxNs > g_firstRxNs) ? (g_lastRxNs - g_firstRxNs) : 0;
  const double gbps = (bytes > 0 && durNs > 0) ? (double) bytes * 8.0 / (double) durNs : 0.0;
  const double gbpsOverall = (bytes > 0 && g_lastRxNs > 100000000)   // from ep0 start (100µs)
                             ? (double) bytes * 8.0 / (double) (g_lastRxNs - 100000000ULL) : 0.0;

  // per-device dump (debug)
  for (uint32_t n = 0; n < SueGetNNodes (); ++n)
    {
      Ptr<Node> node = SueGetDevice (n, 0)->GetNode ();
      for (uint32_t d = 0; d < node->GetNDevices (); ++d)
        {
          Ptr<SueNetDevice> dev = DynamicCast<SueNetDevice> (node->GetDevice (d));
          if (!dev) { continue; }
          std::cout << "    dev[" << n << "][" << d << "]";
          if (dev->GetLlrEngine ())
            {
              const SueLlrCounters &c = dev->GetLlrEngine ()->GetCounters ();
              std::cout << " llr{tx_ok=" << c.tx_ok << " rx_ok=" << c.rx_ok
                        << " replay=" << c.tx_replay << " ack_tx=" << c.tx_ack_ctl_os
                        << " nack_tx=" << c.tx_nack_ctl_os << " nack_rx=" << c.rx_nack_ctl_os
                        << " discard=" << c.tx_discard << "}";
            }
          if (dev->GetCbfcEngine ())
            {
              const SueCbfcCounters &c = dev->GetCbfcEngine ()->GetCounters ();
              std::cout << " cbfc{cf_tx=" << c.cf_update_tx << " cf_rx=" << c.cf_update_rx
                        << " cc_tx=" << c.cc_update_tx << " cc_rx=" << c.cc_update_rx
                        << " cred_exh=" << c.credit_exhausted[0];
              for (int v = 1; v < 8; ++v) { std::cout << "+" << c.credit_exhausted[v]; }
              std::cout << "}";
            }
          std::cout << "\n";
        }
    }

  // aggregate LLR/CBFC counters across devices
  uint64_t sumReplay = 0, sumNackTx = 0, sumNackRx = 0, sumDiscard = 0, sumAckTx = 0;
  uint64_t sumCreditExh = 0;
  for (uint32_t n = 0; n < SueGetNNodes (); ++n)
    {
      Ptr<Node> node = SueGetDevice (n, 0)->GetNode ();
      for (uint32_t d = 0; d < node->GetNDevices (); ++d)
        {
          Ptr<SueNetDevice> dev = DynamicCast<SueNetDevice> (node->GetDevice (d));
          if (!dev) { continue; }
          if (dev->GetLlrEngine ())
            {
              const SueLlrCounters &c = dev->GetLlrEngine ()->GetCounters ();
              sumReplay += c.tx_replay; sumNackTx += c.tx_nack_ctl_os; sumNackRx += c.rx_nack_ctl_os;
              sumDiscard += c.tx_discard; sumAckTx += c.tx_ack_ctl_os;
            }
          if (dev->GetCbfcEngine ())
            {
              const SueCbfcCounters &c = dev->GetCbfcEngine ()->GetCounters ();
              for (int v = 0; v < 8; ++v) { sumCreditExh += c.credit_exhausted[v]; }
            }
        }
    }

  CHECK (sent == frames, "sender sent all " << frames << " frames (tx " << sent << ")");
  if (!llrEna && lossEvery > 0)
    {
      // 无 LLR:坏帧直接丢,交付 = sent - ⌊sent/N⌋(CheckFcs 从 count=1 起算
      // 每 N 帧坏 1 帧的精确计数);无重传可恢复。
      CHECK (recv == frames - expLost, "no-LLR lossy link: delivered == sent - " << expLost
             << " (" << recv << " vs " << frames - expLost << ")");
    }
  else
    {
      CHECK (recv == frames, "receiver got all " << frames << " frames (rx " << recv << ")");
    }
  CHECK (bytes == expectedBytes, "payload bytes complete (" << bytes << "/" << expectedBytes << ")");
  CHECK (sumDiscard == 0, "no LLR discard / FLUSH");
  if (lossEvery > 0)
    {
      if (llrEna)
        {
          CHECK (sumReplay > 0, "loss triggered LLR replay (tx_replay " << sumReplay << ")");
        }
    }
  else
    {
      // §12.25/§12.27 病理回归护栏:两次事故都是"无损但吞吐崩塌"(84% 无谓重传
      // 0.73Gbps@1G、静态定时器 0.46Gbps)——仅"全量无损送达"断言守不住。clean
      // 模式断言:①零重放(无丢失即不应有 replay);②速率 ≥ 95%×线速×有效载荷
      // 占比(payload/(payload+34B 头部/preamble/IFG))。
      CHECK (sumReplay == 0, "clean mode: no spurious replay (got " << sumReplay << ")");
      const double payloadShare = (double) payload / (double) (payload + 14 + 8 + 12);
      const double rateFloor = 0.95 * (bps / 1e9) * payloadShare;
      CHECK (gbps >= rateFloor, "clean mode: rate " << gbps << " >= " << rateFloor
                                 << " Gbps (95% x line x payload share)");
    }

  std::cout << "THPT RESULT mode=" << (lossEvery ? "loss1/" + std::to_string (lossEvery) : "clean")
            << " sent=" << sent << " rx=" << recv << " payload_B=" << bytes
            << " t_firstRx=" << g_firstRxNs << "ns t_lastRx=" << g_lastRxNs << "ns"
            << " dur=" << durNs << "ns"
            << " rate=" << gbps << "Gbps (recv-window) / " << gbpsOverall << "Gbps (from send start)\n"
            << "THPT COUNTERS replay=" << sumReplay << " nack_tx=" << sumNackTx << " nack_rx=" << sumNackRx
            << " ack_tx=" << sumAckTx << " discard=" << sumDiscard << " credit_exhausted=" << sumCreditExh
            << " wall_ms=" << wall << "\n";
  std::cout << (g_ok ? "THPT PASS" : "THPT FAIL") << std::endl;
  Simulator::Destroy ();
  return g_ok ? 0 : 1;
}
