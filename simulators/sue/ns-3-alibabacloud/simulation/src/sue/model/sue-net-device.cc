void
SueNetDevice::OnCtlOsPacingTimer ()
{
  if (m_ctlOsPending.empty ()) { return; }
  Ptr<Packet> p = m_ctlOsPending.front ();
  m_ctlOsPending.pop_front ();
  m_ctlOsFirstTx = false;
  m_lastCtlOsTx = Simulator::Now ();
  TransmitControl (p);
  // Drain the rest of the burst at the configured cadence (keeps FIFO order).
  if (!m_ctlOsPending.empty ())
    {
      m_ctlOsEvent = ScheduleSelf (m_ctlOsMinInterval,
                                   &SueNetDevice::OnCtlOsPacingTimer, this);
    }
}

void
SueNetDevice::SendCtlFrame (SueCtlHeader::CtlType type, Ptr<Packet> payload)
{
  // Build control frame: prepend SueCtlHeader to the payload packet.
  // This path is for CtlOS short messages only (LLR ACK/NACK/INIT/INIT_ECHO,
  // CBFC CF_UPDATE). PFC/CC_Update are real Ethernet frames and are sent via
  // TransmitControl directly (no SueCtlHeader on the wire).
  SueCtlHeader ctl (type);
  payload->AddHeader (ctl);                 // [SueCtlHeader][payload headers/data]
  SueCtlTag tag;
  tag.SetType (type);
  payload->AddPacketTag (tag);

  // Optional pacing gate: enforce a min interval between successive CtlOS
  // transmissions. m_lastCtlOsTx is stamped at admission time; because the
  // pending deque drains at exactly the min-interval cadence, the steady-state
  // wire rate is bounded by 1/interval. Queueing behind a busy link only adds
  // spacing, never reduces it.
  //
  // Priority (UEC §5.1.9.1.5 Table 5-12): LLR_INIT / LLR_INIT_ECHO are the
  // highest and LLR_ACK / LLR_NACK the lowest LLR priorities (no priority
  // difference between ACK and NACK — LLR never sends both at once); CBFC
  // CtlOS (CF_UPDATE) is strictly BELOW LLR_ACK/LLR_NACK. The control queue is
  // a single FIFO (DESIGN §12.11 — no per-type sub-priority modelled), so all
  // CtlOS transmit in admission order and CF_UPDATE is never expedited ahead
  // of ACK/NACK. ACKs stay continuous (idle repeats — the chip sends them on
  // the ctlos_target_spacing cadence even when idle). Consequence: with
  // LLR_CTLOS_TARGET_SPACING driving BOTH the pacing slot and the ACK period
  // (DESIGN.md line 773 coupling), the continuous ACK stream can occupy every
  // CtlOS slot on the return link and the lowest-priority CF_UPDATE must wait
  // for free slots — refund latency (and therefore credit-window throughput)
  // is bounded by the ACK cadence, not by any queue priority.
  if (m_ctlOsMinInterval > Seconds (0))
    {
      if (!m_ctlOsFirstTx && Simulator::Now () < m_lastCtlOsTx + m_ctlOsMinInterval)
        {
          m_ctlOsPending.push_back (payload);
          if (!m_ctlOsEvent.IsRunning ())
            {
              m_ctlOsEvent = ScheduleSelf (m_lastCtlOsTx + m_ctlOsMinInterval - Simulator::Now (),
                                           &SueNetDevice::OnCtlOsPacingTimer, this);
            }
          return;
        }
      m_ctlOsFirstTx = false;
      m_lastCtlOsTx = Simulator::Now ();
    }
  TransmitControl (payload);
}

void
SueNetDevice::SendCtlAckNack (uint32_t seq, bool isNack)
{
  Ptr<Packet> pl = Create<Packet> ();
  SueLlrCtlOsHeader h;
  if (isNack) { h.SetNack (seq); } else { h.SetAck (seq); }
  pl->AddHeader (h);
  SendCtlFrame (isNack ? SueCtlHeader::LLR_NACK : SueCtlHeader::LLR_ACK, pl);
}

