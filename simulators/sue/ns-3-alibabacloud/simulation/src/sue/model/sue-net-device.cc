void SueNetDevice::SetLlrEngine (Ptr<SueLlrEngine> llr)
{
  m_llr = llr; m_llrEnabled = true;
  // NS3_MTP (§10.5): bind the engine's timers to this node's context so they
  // execute/cancel on the owning logical process. The default simulator ignores
  // context, so this is behavior-neutral outside MTP.
  if (GetNode ()) { llr->SetContext (GetNode ()->GetId ()); }
  llr->SetRetransmitCb (MakeCallback (&SueNetDevice::Retransmit, this));
  llr->SetStateChangeCb (MakeCallback (&SueNetDevice::OnLlrStateChange, this));
  // Partial-ACK wakeup: an ACK/NACK freeing window space (buffer not empty)
  // re-runs the dequeue so TX doesn't stop-and-go at window granularity.
  llr->SetTxOpportunityCb (MakeCallback (&SueNetDevice::OnLlrTxOpportunity, this));
  // §5.2.9 rules 3/9: the engine drives the LLR window (REPLAY state / NACK
  // sent) into the CBFC engine, so the gates cover the REAL windows that span
  // many events — not just the synchronous retransmit call (see A6/B2).
  llr->SetLlrWindowCb (MakeCallback (&SueNetDevice::FcSuspendForLlrWindow, this));
  // On-wire: ACK/NACK/INIT sent via channel (no manual peer wiring needed).
  llr->SetAckNackSink (MakeCallback (&SueNetDevice::SendCtlAckNack, this));
  llr->SetInitSink (MakeCallback (&SueNetDevice::SendCtlInit, this));
  llr->SetInitEchoSink (MakeCallback (&SueNetDevice::SendCtlInitEcho, this));
}

