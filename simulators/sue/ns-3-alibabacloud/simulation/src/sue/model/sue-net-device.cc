void
SueNetDevice::SendCtlCfUpdate (uint32_t vc, uint32_t cf)
{
  if (m_cbfc) { m_cbfc->IncCfUpdateTx (); }
  Ptr<Packet> pl = Create<Packet> ();
  SueCbfcCtlOsHeader h;
  h.SetEntry (0, vc, cf);
  pl->AddHeader (h);
  SendCtlFrame (SueCtlHeader::CF_UPDATE, pl);
}

void
SueNetDevice::SetCfUpdateTimers (Time minInterval, Time maxInterval)
{
  m_cfMinInterval = minInterval;
  m_cfMaxInterval = maxInterval;
  m_cfDirtyMask = 0;
  m_cfMinTimer.Cancel ();
  m_cfMaxTimer.Cancel ();
  // UEC trigger 2: a periodic full update of all R_VC_CF (loss resilience).
  // CBFC only — PFC/OFF have no CF_Update path and never call
  // SetCfUpdateTimers with a CBFC engine. Config runs on the public LP at
  // setup, so under MTP defer the arm to the owning node's LP (same pattern
  // as StartCcUpdateTimer); otherwise arm directly (node context).
  if (m_cfMaxInterval > Seconds (0) && m_cbfc)
    {
      if (SueMtpActive () && GetNode ())
        {
          Simulator::ScheduleWithContext (GetNode ()->GetId (), TimeStep (0),
                                          &SueNetDevice::ArmCfUpdateTimerOnLp, this,
                                          m_cfMaxInterval);
          return;
        }
      m_cfMaxTimer = ScheduleSelf (m_cfMaxInterval, &SueNetDevice::OnCfMaxTimer, this);
    }
}

void
SueNetDevice::ArmCfUpdateTimerOnLp (Time maxInterval)
{
  m_cfMaxTimer = ScheduleSelf (maxInterval, &SueNetDevice::OnCfMaxTimer, this);
}

void
SueNetDevice::OnCfDirty (uint32_t vc)
{
  if (vc < SueCbfcEngine::NVC) { m_cfDirtyMask |= (1u << vc); }
  // UEC §5.2.6.1 trigger 1: R_VC_CF[vc] updated. Arm the CF_min one-shot if
  // it isn't already running, at m_lastCfUpdate + CF_min — the fixed
  // min-interval after the LAST CF_Update, NOT Now + CF_min. Because the fire
  // time is computed from shared state (m_lastCfUpdate) rather than the
  // arming drain's clock, the one-shot fires on a deterministic grid
  // regardless of which drain armed it: a boundary drain that coincides with
  // the fire time can shift the batch CONTENT but never the fire TIMES or the
  // send COUNT (MTP equivalence, §10.5). The max() guard covers the idle-gap
  // case where CF_min has already elapsed when the first post-idle drain
  // arrives (fire immediately, at the drain's own timestamp).
  if (m_cfMinInterval > Seconds (0) && !m_cfMinTimer.IsRunning ())
    {
      // arm is an ABSOLUTE fire time; ScheduleSelf takes a RELATIVE delay, so
      // schedule (arm - Now) — passing arm raw would double the interval
      // (fire at Now + arm). The max() guard covers the idle-gap case where
      // CF_min has already elapsed when the first post-idle drain arrives.
      Time arm = std::max (Simulator::Now (), m_lastCfUpdate + m_cfMinInterval);
      Time delay = arm - Simulator::Now ();
      // arm == Now in the idle-gap case (CF_min already elapsed): Schedule()
      // rejects a non-positive delay, so floor the relative delay at one time
      // step — the fire is still "immediate" at the drain's timestamp grid and
      // stays on the owning node's LP (deterministic under MTP, §10.5).
      if (delay <= Seconds (0)) { delay = TimeStep (1); }
      m_cfMinTimer = ScheduleSelf (delay, &SueNetDevice::OnCfMinTimer, this);
    }
}

void
SueNetDevice::OnCfMinTimer (void)
{
  // CF_min elapsed: report every VC updated since the last CF_Update. An
  // empty dirty mask means the periodic CF_max full update (which cancels
  // this timer) already covered everything — send nothing.
  if (m_cfDirtyMask != 0)
    {
      SendCfUpdateBatch (m_cfDirtyMask);
      m_cfDirtyMask = 0;
      m_lastCfUpdate = Simulator::Now ();
    }
}

void
SueNetDevice::OnCfMaxTimer (void)
{
  // UEC §5.2.6.1 trigger 2: periodic full update — report every VC's current
  // R_VC_CF so a lost CF_Update cannot strand credits (loss resilience). The
  // full update subsumes any pending CF_min flush: cancel the one-shot (both
  // timers are local events on this device's LP, so the cancellation is
  // deterministic) and clear the dirty mask before sending.
  if (m_cfMinTimer.IsRunning ()) { m_cfMinTimer.Cancel (); }
  uint16_t allVc = 0;
  for (uint32_t vc = 0; vc < SueCbfcEngine::NVC; ++vc) { allVc |= (1u << vc); }
  SendCfUpdateBatch (allVc);
  m_cfDirtyMask = 0;
  m_lastCfUpdate = Simulator::Now ();
  if (m_cfMaxInterval > Seconds (0))
    {
      m_cfMaxTimer = ScheduleSelf (m_cfMaxInterval, &SueNetDevice::OnCfMaxTimer, this);
    }
}

void
SueNetDevice::SendCfUpdateBatch (uint16_t vcMask)
{
  uint16_t mask = vcMask & ((1u << SueCbfcEngine::NVC) - 1);
  while (mask)
    {
      // Pack up to 2 (VC, CF) entries per 8B message (§5.6); iterate the set
      // bits from lowest VC.
      uint32_t vc1 = 0, vc2 = 0;
      uint16_t m = mask;
      uint32_t low = 0;
      while (!(m & 1u)) { m >>= 1u; ++low; }
      vc1 = low; mask &= ~(1u << vc1);
      uint16_t m2 = mask;
      if (m2)
        {
          uint32_t low2 = 0;
          while (!(m2 & 1u)) { m2 >>= 1u; ++low2; }
          vc2 = low2; mask &= ~(1u << vc2);
        }
      if (m_cbfc) { m_cbfc->IncCfUpdateTx (); }
      Ptr<Packet> pl = Create<Packet> ();
      SueCbfcCtlOsHeader h;
      uint32_t cf1 = m_fc ? m_fc->GetRvcCf (vc1) : m_cbfc->GetRvcCf (vc1);
      uint32_t cf2 = 0;
      if (m2) { cf2 = m_fc ? m_fc->GetRvcCf (vc2) : m_cbfc->GetRvcCf (vc2); }
      h.SetEntry (0, vc1, cf1);
      if (m2) { h.SetEntry (1, vc2, cf2); }
      pl->AddHeader (h);
      SendCtlFrame (SueCtlHeader::CF_UPDATE, pl);
    }
}

void
SueNetDevice::SendCtlCcUpdate (void)
{
  if (!m_cbfc) { return; }
  // §5.2.9 rule 9: no CC_Update inside an LLR window (replayed frames would be
  // double-counted as a leak). The periodic OnCcUpdateTimer goes through here.
  if (m_cbfc->GetInLlrWindow ()) { return; }
  m_cbfc->IncCcUpdateTx ();
  // Real 64B Ethernet frame (DESIGN §5.6): MACDA|MACSA|EtherType=0x8808|
  // Opcode=0xFFFE|CID|MsgType|16x20b CC|FCS. VC[8:15] are 0 (8 VC generation).
  Ptr<Packet> pl = Create<Packet> ();
  SueCbfcCcHeader cch;
  cch.SetMacSa (GetMacSa ());
  cch.SetMacDa (m_ccUpdateMacDa);   // §5.2.6.2 configurable (default = spec value)
  cch.SetCid (m_ccUpdateCid);
  for (uint32_t v = 0; v < SueCbfcCcHeader::NVC; ++v) { cch.SetCc (v, m_cbfc->GetSvcCc (v)); }
  pl->AddHeader (cch);
  SueCtlTag tag;
  tag.SetType (SueCtlHeader::CC_UPDATE);
  pl->AddPacketTag (tag);
  TransmitControl (pl);
}

void
SueNetDevice::StartCcUpdateTimer (Time interval)
{
  m_ccUpdateInterval = interval;
  if (interval > Seconds (0) && m_cbfc)
    {
      if (SueMtpActive () && GetNode ())
        {
          // §10.5 MTP: config runs on the public LP at setup; defer the CC_Update
          // cadence arm to the owning node's LP (see SueLlrEngine::Start).
          Simulator::ScheduleWithContext (GetNode ()->GetId (), TimeStep (0),
                                          &SueNetDevice::ArmCcUpdateTimerOnLp, this,
                                          interval);
          return;
        }
      m_ccUpdateTimer = ScheduleSelf (interval, &SueNetDevice::OnCcUpdateTimer, this);
    }
}

void
SueNetDevice::ArmCcUpdateTimerOnLp (Time interval)
{
  m_ccUpdateTimer = ScheduleSelf (interval, &SueNetDevice::OnCcUpdateTimer, this);
}

void
SueNetDevice::OnCcUpdateTimer (void)
{
  SendCtlCcUpdate ();
  if (m_ccUpdateInterval > Seconds (0))
    {
      m_ccUpdateTimer = ScheduleSelf (m_ccUpdateInterval, &SueNetDevice::OnCcUpdateTimer, this);
    }
}

