uint8_t
SueNetDevice::ComputeVc (const SueHeader &h) const
{
  // DESIGN §7: table-driven, end-to-end consistent with the sender and the
  // switch (all read the same SueConfig map). Default table = direct map
  // (dscp&0x07 / pcp identity), so this is behavior-identical for any config
  // that does not override DSCP_TO_VC_MAP / PCP_TO_VC_MAP.
  if (h.HasShim ()) { return SueConfig::DscpToVc (h.GetShim ().dscp); }
  if (h.HasVlan ()) { return SueConfig::PcpToVc (h.GetPcp (), h.GetDei ()); }
  return SueConfig::DefaultVc ();
}

bool
SueNetDevice::SwitchSend (uint32_t qIndex, Ptr<Packet> p)
{
  // §12.50 debug guard: the caller's queue index MUST equal the frame's
  // derived VC (shim DSCP > VLAN PCP > default). A mismatch silently splits
  // the credit charge (OnTx uses the dequeue VC = qIndex) from the refund
  // (the switch's Forward uses ComputeVc) across DIFFERENT VCs — CU=(CC-CF)
  // mod 2^15 flips to a huge value and the window blocks permanently. This
  // exact bug halved the AXI workload bandwidth for a week before the credit
  // audit exposed it (§12.50). Non-SUE frames (header parse fails) skip the
  // check. NS_ASSERT is compiled out in release builds — zero runtime cost
  // there, loud failure in every debug/test build.
  SueHeader h;
  if (p->PeekHeader (h))
    {
      const uint8_t vc = ComputeVc (h);
      NS_ASSERT_MSG (qIndex == vc,
                     "SwitchSend qIndex=" << qIndex << " != frame-derived VC=" << (uint32_t) vc
                     << " (credit charge/refund would land on different VCs, §12.50)");
    }
  if (m_queue) { m_queue->Enqueue (qIndex, p); if (!m_busy) { DequeueAndTransmit (); } }
  else { if (!m_busy) { TransmitStart (p); } }
  return true;
}

void
SueNetDevice::DequeueAndTransmit (void)
{
  if (m_busy || !m_queue) { return; }
  // LLR TX gate (UEC §5.1.4/§5.1.5): per-state handling of new LLR-desired
  // frames. BLOCK -> don't take frames (stay queued, lossless);
  // LLR_ACTIVE additionally enforces the ADVANCE + outstanding limits;
  // DISCARD / BEST_EFFORT -> proceed to take a frame.
  if (m_llr)
    {
      SueLlrEngine::TxBehavior b = m_llr->GetTxBehavior ();
      if (b == SueLlrEngine::TxBehavior::BLOCK) { return; }
      if (b == SueLlrEngine::TxBehavior::LLR_ACTIVE && !m_llr->CanTx ()) { return; }
    }
  // DISCARD style (INIT/FLUSH with llr_{init,flush}_behavior=DISCARD): take +
  // drop without FC credit or wire transmission, until the queue empties or a
  // non-DISCARD frame is reached (UEC: DISCARD counted in tx_discard).
  if (m_llr && m_llr->GetTxBehavior () == SueLlrEngine::TxBehavior::DISCARD)
    {
      while (!m_busy && m_queue
             && m_llr->GetTxBehavior () == SueLlrEngine::TxBehavior::DISCARD)
        {
          int dq = m_queue->GetNextQindex ();
          if (dq < 0) { return; }
          m_queue->Dequeue (dq);
          m_llr->DiscardNew ();
        }
      if (m_busy || !m_queue) { return; }
    }
  // Flow-control gate: facade if set, else legacy CBFC credit / PFC pause
  int q;
  if (m_fc) { q = m_queue->GetNextSendableQindex (m_fc); }
  else if (m_pfc) { q = m_queue->GetNextSendableQindexPfc (m_pfc); }
  else { q = m_queue->GetNextSendableQindex (m_cbfc); }
  if (q < 0) { return; }
  Ptr<Packet> p = m_queue->Dequeue ((uint32_t) q);
  if (m_fc) { m_fc->OnTx ((uint32_t) q, p->GetSize ()); }
  else if (m_cbfc) { m_cbfc->OnTx ((uint32_t) q, p->GetSize ()); }
  if (m_llr)
    {
      SueLlrEngine::TxBehavior b = m_llr->GetTxBehavior ();
      if (b == SueLlrEngine::TxBehavior::LLR_ACTIVE)
        {
          // Eligible frame: assign seq + store a CLEAN copy in the replay
          // buffer (the stored MAC frame must NOT carry the wire preamble —
          // PrependLlrPreamble mutates the packet in place, so storing p and
          // then prepending would leave the buffer entry pre-preamble'd and
          // every later retransmit would prepend AGAIN -> double preamble ->
          // the RX-side PeekHeader reads the second preamble as the SueHeader
          // and routing misses). The live frame p is unique to this TX.
          uint32_t seq = m_llr->TxStore (p->Copy ());
          m_llr->StartReplayTimer ();
          // COUNTER-007 (§5.1.10): TX-side FCS poisoning — the frame carries
          // SueFrameBadTag to the peer (packet tags survive the channel), which
          // classifies it POISONED: accepted, no NACK, frame_bad set.
          if (m_errModel && m_errModel->CheckPoisonTx ())
            {
              SueFrameBadTag fb;
              p->AddPacketTag (fb);
              m_llr->IncTxPoisoned ();
            }
          PrependLlrPreamble (p, seq, true);
        }
      else
        {
          // UEC §5.1.1.1/§5.1.5: BEST_EFFORT (mode_remote OFF / LLR_OFF)
          // frames are LLR-ineligible — they still carry the standard 8B
          // ineligible preamble so the receiver keeps its SUE-header parse
          // aligned (no seq / replay / seq filter).
          PrependLlrPreamble (p, 0, false);
        }
    }
  else if (m_llrEnabled)
    {
      PrependLlrPreamble (p, m_llrSeq++, true);
    }
  TransmitStart (p);
  // CBFC egress→ingress backpressure (§12.30): an egress slot was freed (the
  // frame we just took is now on the wire, m_busy=true). Fire the switch hook
  // so it can ServicePending. SwitchSend from the hook only enqueues (m_busy
  // blocks a re-entrant DequeueAndTransmit); the next TransmitComplete picks
  // the admitted frame up. Fired here (after TransmitStart) precisely so
  // m_busy==true and the pending service can never recurse.
  if (m_egressFreedHook) { m_egressFreedHook (); }
}

void
SueNetDevice::Retransmit (uint32_t seq, Ptr<Packet> macFrame)
{
  // Dedup: don't enqueue if seq already in retx queue (prevents unbounded
  // growth during wire-busy backlogs; the frame is still in the LLR replay
  // buffer)
  for (const auto &e : m_retxQueue) { if (e.seq == seq) { return; } }
  if (m_busy) { m_retxQueue.push_back ({seq, macFrame}); return; }
  // UEC §5.1: a PFC pause frame does NOT stop LLR replay — pause gates new
  // data frames only. Gating retransmits here would (a) violate the spec and
  // (b) pile up replay_ct under pause+NACK until a FLUSH discards frames that
  // a replay would have recovered.
  // §5.2.9 rule 1: replay frames already counted; do NOT update S_VC_CC
  // (structural — this path never calls OnTx). The rules-3/9 LLR window is
  // driven by the LLR engine state now (SetLlrWindowCb), not held here.
  // Transmit a fresh copy: macFrame is the LLR engine's shared replay-buffer
  // entry and must stay preamble-free (PrependLlrPreamble mutates in place).
  Ptr<Packet> tx = macFrame->Copy ();
  PrependLlrPreamble (tx, seq, true);   // retransmits are always eligible
  TransmitStart (tx);
}

bool
SueNetDevice::DrainRetx ()
{
  if (m_busy || m_retxQueue.empty ()) { return false; }
  RetxEntry e = m_retxQueue.front ();
  // UEC §5.1: PFC pause does NOT stop LLR replay (see Retransmit).
  m_retxQueue.pop_front ();
  // §5.2.9 rule 1: replay frames already counted; do NOT update S_VC_CC
  // (structural). The LLR window is engine-driven (SetLlrWindowCb).
  // Fresh copy: e.p may alias the engine's shared replay-buffer entry.
  Ptr<Packet> tx = e.p->Copy ();
  PrependLlrPreamble (tx, e.seq, true);   // retransmits are always eligible
  TransmitStart (tx);
  return true;
}

bool
SueNetDevice::TransmitStart (Ptr<Packet> p)
{
  NS_ASSERT_MSG (m_channel, "no channel");
  Time txTime = GetDataRate ().CalculateBytesTxTime (p->GetSize ());
  m_busy = true;
  m_channel->TransmitStart (p, this, txTime);
  ScheduleSelf (txTime, &SueNetDevice::TransmitComplete, this);
  return true;
}

void
SueNetDevice::TransmitComplete (void)
{
  m_busy = false;
  // Priority: control queue > retx queue > data queue
  if (!m_ctlQueue.empty ())
    {
      Ptr<Packet> ctl = m_ctlQueue.front ();
      m_ctlQueue.pop_front ();
      TransmitStart (ctl);
      return;
    }
  if (DrainRetx ()) { return; }
  if (m_ifg > Seconds (0)) { ScheduleSelf (m_ifg, &SueNetDevice::DequeueAndTransmit, this); }
  else { DequeueAndTransmit (); }
}

