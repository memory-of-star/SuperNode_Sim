void
SueNetDevice::SetCtlOsTargetSpacing (uint32_t bytes)
{
  // UEC ctlos_target_spacing: bytes of wire time between successive CtlOS.
  // Requires the link data rate to be set first (PointToPointNetDevice
  // defaults to a 32768 b/s placeholder, not a real link rate). Uses the
  // explicit IsDataRateSet flag, not a comparison against the placeholder.
  NS_ASSERT_MSG (IsDataRateSet (),
                 "SetCtlOsTargetSpacing(): link data rate not configured "
                 "(still PointToPoint default 32kb/s); call SetDataRate () first "
                 "or use SetCtlOsMinInterval () with an explicit Time");
  SetCtlOsMinInterval (GetDataRate ().CalculateBytesTxTime (bytes));
}

