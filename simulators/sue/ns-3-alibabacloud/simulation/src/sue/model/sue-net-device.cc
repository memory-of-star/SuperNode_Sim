void
SueNetDevice::SendCtlPause (uint32_t vc, bool isPause)
{
  // Real 802.1Qbb Ethernet frame (DESIGN §5.10): MACDA|MACSA|EtherType=0x8808|
  // Opcode=0x0101|PEV|8xquanta|pad|FCS = 64B on the wire. quanta>0 pauses a
  // priority, quanta=0 resumes it (802.1Qbb semantic); PEV marks the VC.
  Ptr<Packet> pl = Create<Packet> ();
  SuePfcHeader h;
  h.SetMacSa (GetMacSa ());
  h.SetQuanta (vc, isPause ? m_pfcPauseQuanta : 0);
  pl->AddHeader (h);
  SueCtlTag tag;
  tag.SetType (isPause ? SueCtlHeader::PFC_PAUSE : SueCtlHeader::PFC_RESUME);
  pl->AddPacketTag (tag);
  TransmitControl (pl);
}

// --- CtlOS on-wire RX dispatch ---
void
SueNetDevice::HandleCtlFrame (Ptr<Packet> p, SueCtlHeader::CtlType type)
{
  // CtlOS short messages (LLR ACK/NACK/INIT/INIT_ECHO, CF_Update) carry the
  // 1B SueCtlHeader on the wire; remove it to align the buffer before parsing
  // the payload. PFC/CC_Update are real Ethernet frames (no SueCtlHeader).
  switch (type)
    {
    case SueCtlHeader::LLR_ACK:
    case SueCtlHeader::LLR_NACK:
      {
        SueCtlHeader ctl;
        p->RemoveHeader (ctl);
        SueLlrCtlOsHeader ctlos;
        p->RemoveHeader (ctlos);
        if (m_llr) { m_llr->OnAckNack (ctlos.GetSeq (), type == SueCtlHeader::LLR_NACK); }
        break;
      }
    case SueCtlHeader::LLR_INIT:
      {
        SueCtlHeader ctl;
        p->RemoveHeader (ctl);
        SueLlrCtlOsHeader ctlos;
        p->RemoveHeader (ctlos);
        if (m_llr)
          {
            m_llr->OnInit (ctlos.GetSeq (), ctlos.GetInitData ());   // resets next_rx_seq + echoes init_data
            DequeueAndTransmit ();
          }
        break;
      }
    case SueCtlHeader::LLR_INIT_ECHO:
      {
        SueCtlHeader ctl;
        p->RemoveHeader (ctl);
        SueLlrCtlOsHeader ctlos;
        p->RemoveHeader (ctlos);
        if (m_llr) { m_llr->OnInitEcho (ctlos.GetSeq (), ctlos.GetInitData ()); }   // sender -> ADVANCE
        break;
      }
    case SueCtlHeader::LLDP:
      {
        // UE link negotiation (UEC §5.3, NEG-SP-01/02 + CBFC-SP-13 §5.2.8.4):
        // store the peer TLV and run the handshake state machine (first frame
        // adopts parameters and starts LLR; every frame advances RTS/RTR).
        SueCtlHeader ctl;
        p->RemoveHeader (ctl);
        SueLldpHeader lldp;
        p->RemoveHeader (lldp);
        m_lldpRemote = lldp;
        m_lldpRemoteRcvd = true;
        OnRemoteLldpTlv ();
        break;
      }
    case SueCtlHeader::CF_UPDATE:
      {
        SueCtlHeader ctl;
        p->RemoveHeader (ctl);
        SueCbfcCtlOsHeader ctlos;
        p->RemoveHeader (ctlos);
        if (m_cbfc)
          {
            m_cbfc->IncCfUpdateRx ();
            m_cbfc->OnCfUpdate (ctlos.GetVc (0), ctlos.GetCount (0));
            if (ctlos.GetVc (1) || ctlos.GetCount (1))
              { m_cbfc->OnCfUpdate (ctlos.GetVc (1), ctlos.GetCount (1)); }
            DequeueAndTransmit ();   // credits reclaimed -> resume queued frames
          }
        break;
      }
    case SueCtlHeader::CC_UPDATE:
      {
        // Real 64B Ethernet frame (DESIGN §5.6), no SueCtlHeader.
        SueCbfcCcHeader cch;
        p->RemoveHeader (cch);
        if (m_cbfc)
          {
            // §12.48 (UEC §5.2.9 note 3 rationale): with frames discarded in
            // the last NACK window not yet all re-accepted (in-flight
            // GoBackN retransmits), the CC check is INVALID — processing the
            // LostCredits now refunds the in-flight retransmits; they refund
            // again on landing (double refund → CU mod-2^15 flip → permanent
            // credit block). Drop the whole message, same as rule 3 inside
            // the (spec-literal) discard window; the next CC period retries.
            if (m_llr && m_llr->HasPendingDiscard ())
              {
                NS_LOG_LOGIC ("CC_Update dropped: GoBackN retransmits in flight (pending discard)");
                break;
              }
            m_cbfc->IncCcUpdateRx ();
            std::array<uint32_t, 16> cc{};
            for (uint32_t v = 0; v < 16; ++v) { cc[v] = cch.GetCc (v); }
            m_cbfc->OnCcUpdate (cc);   // recover leaked credits (receiver side)
            // The recovered credit returns to the sender via the next CF_Update.
          }
        break;
      }
    case SueCtlHeader::PFC_PAUSE:
    case SueCtlHeader::PFC_RESUME:
      {
        // Real 802.1Qbb frame (DESIGN §5.10), no SueCtlHeader. Decode by
        // the frame's PEV/quanta (802.1Qbb semantic): quanta>0 pauses that
        // priority, quanta=0 resumes it.
        SuePfcHeader pf;
        p->RemoveHeader (pf);
        bool resumed = false;
        if (m_pfc)
          {
            uint16_t pev = pf.GetPev ();
            for (uint32_t vc = 0; vc < SuePfcHeader::NVC; ++vc)
              {
                if (pev & (1u << vc))
                  {
                    if (pf.GetQuanta (vc) > 0) { m_pfc->OnPause (vc); }
                    else
                      {
                        m_pfc->OnResume (vc);
                        if (!resumed) { resumed = true; }
                      }
                  }
              }
          }
        if (resumed) { DrainRetx (); DequeueAndTransmit (); }
        break;
      }
    default:
      break;
    }
}

void
SueNetDevice::OnLlrStateChange ()
{
  // Engine returned to ADVANCE (ACK complete or FLUSH+INIT): clear stale
  // retransmit queue, then resume new-frame dequeue.
  m_retxQueue.clear ();
  DequeueAndTransmit ();
}

void
SueNetDevice::OnLlrTxOpportunity ()
{
  // Partial window release (LLR buffer not yet empty): just re-attempt the
  // dequeue. Do NOT clear m_retxQueue here (that is OnLlrStateChange's job —
  // mid-REPLAY retransmits must survive).
  DequeueAndTransmit ();
}

// ---- UE link negotiation (UEC §5.3, NEG-SP-01/02) ----
void
SueNetDevice::EnableLldpNegotiation ()
{
  m_lldpNegotiate = true;
}

void
SueNetDevice::StartLldpExchange ()
{
  if (!m_lldpNegotiate) { return; }
  // Local capability TLV from the configured engines.
  m_lldpLocal.SetLlrSupported (m_llr != nullptr);
  if (m_cbfc)
    {
      // Advertise the receiver-native cell (GetCreditSize == rx): the peer's
      // sender snaps down to it via AdoptTxCellFromPeerRx (§5.2.8.2).
      m_lldpLocal.SetCreditSize (m_cbfc->GetCreditSize ());
      m_lldpLocal.SetPktOvhd (m_cbfc->GetPktOvhd ());
      m_lldpLocal.SetNumVcs (SueCbfcEngine::NVC);
      for (uint8_t v = 0; v < SueCbfcEngine::NVC; ++v)
        {
          m_lldpLocal.SetVcLimit (v, m_cbfc->GetVcCreditLimit (v));
        }
    }
  // §5.2.8.4 (CBFC-SP-13): snapshot the receiver-side want bitmap from the
  // DIRECT-CONFIG limits (before any peer adoption), gate every VC off until
  // its RTS/RTR handshake completes, and advertise want in the first frame.
  m_lldpWant = 0;
  if (m_cbfc)
    {
      for (uint8_t v = 0; v < SueCbfcEngine::NVC; ++v)
        {
          if (m_cbfc->GetVcCreditLimit (v) > 0)
            {
              m_lldpWant |= (uint8_t) (1u << v);
              m_lldpLocal.SetRvcWant (v, true);
            }
          m_cbfc->SetVcLosslessActive (v, false);
        }
    }
  SendLldpWithState ();
  // No peer (isolated device / test wiring): fall back to local-only config
  // so the engines still start instead of hanging in negotiation forever.
  m_lldpFallbackTimer = ScheduleSelf (MicroSeconds (10), &SueNetDevice::ApplyLldpFallback, this);
}

void
SueNetDevice::SendLldpWithState ()
{
  for (uint8_t v = 0; v < SueCbfcEngine::NVC; ++v)
    {
      m_lldpLocal.SetSvcRts (v, (m_lldpRts >> v) & 1u);
      m_lldpLocal.SetRvcRtr (v, (m_lldpRtr >> v) & 1u);
    }
  Ptr<Packet> pl = Create<Packet> ();
  pl->AddHeader (m_lldpLocal);
  SueCtlHeader ctl (SueCtlHeader::LLDP);
  pl->AddHeader (ctl);
  SueCtlTag tag;
  tag.SetType (SueCtlHeader::LLDP);
  pl->AddPacketTag (tag);
  TransmitControl (pl);
}

void
SueNetDevice::OnRemoteLldpTlv ()
{
  // Direct-config devices (LLDP_NEGOTIATE=0) ignore LLDP frames entirely —
  // otherwise an unnegotiated peer's reply would cancel the other side's
  // no-peer fallback (its TLV carries no want bitmap) and deadlock the link.
  if (!m_lldpNegotiate) { return; }
  // First frame only (adopt-once, UEC §5.2.8.4: credit size / overhead must
  // not change while lossless VCs are active): cancel the no-peer fallback,
  // adopt the peer's advertised CBFC parameters, and start the LLR engines.
  // Deliberately NOT a one-shot gate for the whole function — a fallback that
  // fires first must not swallow a late real peer frame, and the RTS/RTR
  // state machine below runs on EVERY frame.
  if (!m_lldpFirstRemoteApplied)
    {
      m_lldpFirstRemoteApplied = true;
      if (m_lldpFallbackTimer.IsRunning ()) { m_lldpFallbackTimer.Cancel (); }

      // Options TLV: LLR runs only when BOTH ends support it (UEC §5.3.2.1) —
      // otherwise the link degrades to BEST_EFFORT TX / unfiltered RX.
      const bool both = m_lldpLocal.GetLlrSupported () && m_lldpRemote.GetLlrSupported ();
      if (m_llr)
        {
          if (!both)
            {
              NS_LOG_WARN ("LLDP: peer does not support LLR — link degraded to BEST_EFFORT");
              m_llr->SetModeRemote (false);
              m_llr->SetModeLocal (false);
            }
          m_llr->Start ();   // INIT handshake (now with the negotiated modes)
        }
      // CBFC TLV: the sender adopts the receiver's advertised native RX cell
      // as its TX granularity (snapped down to a supported choice, §5.2.8.2 /
      // §5.2.10.1) plus the packet overhead / per-VC credit limits (the
      // offered VCs only). Only the TX cell is written — the local RX cell is
      // this receiver's own buffer property and is never modified by
      // adoption, so each direction runs homogeneous (local.tx == peer.rx)
      // while the two directions may legitimately differ (SC-26 256<->64).
      if (m_cbfc && m_lldpRemote.GetCreditSize () > 0)
        {
          m_cbfc->AdoptTxCellFromPeerRx (m_lldpRemote.GetCreditSize ());
          m_cbfc->SetPktOvhd (m_lldpRemote.GetPktOvhd ());
          for (uint8_t v = 0; v < SueCbfcEngine::NVC; ++v)
            {
              const uint32_t limit = m_lldpRemote.GetVcLimit (v);
              if (limit > 0) { m_cbfc->SetVcCreditLimit (v, limit); }
            }
        }
      // ULL-CBFC-INIT-001 (UEC §5.2.8.1): NumVCs and the lossless-VC set must
      // be identical at both ends. creditSize/pktOvhd/vcLimit VALUES may
      // legitimately differ per direction (SC-26's asymmetric 256<->64), so
      // only the structural mismatches warn — and adoption still proceeds:
      // the RTS/RTR gate already holds unwanted VCs off the wire (TS-50).
      if (m_lldpRemote.GetNumVcs () != m_lldpLocal.GetNumVcs ())
        {
          m_lldpNumVcsMismatch = true;
          NS_LOG_WARN ("LLDP: peer NumVCs " << (uint32_t) m_lldpRemote.GetNumVcs ()
                       << " != local " << (uint32_t) m_lldpLocal.GetNumVcs ()
                       << " (UEC §5.2.8.1 requires both ends identical)");
        }
      if (m_lldpRemote.GetRvcWantBitmap () != m_lldpLocal.GetRvcWantBitmap ())
        {
          m_lldpLosslessSetMismatch = true;
          NS_LOG_WARN ("LLDP: lossless-VC want set mismatch — local 0x" << std::hex
                       << (uint32_t) m_lldpLocal.GetRvcWantBitmap () << " vs remote 0x"
                       << (uint32_t) m_lldpRemote.GetRvcWantBitmap () << std::dec
                       << " (UEC §5.2.8.1)");
        }
    }

  // §5.2.8.4 state machine (every frame): ASSIGNMENT, not monotone OR —
  // rts = remote want, rtr = remote rts & local want. Static inputs converge
  // in <=3 rounds per end (identical to the old OR); a TRUE->FALSE want flip
  // (ULL-NEG-CBF-RCV-006 / §5.2.8.5 VC removal) now clears S_VC_RTS so the
  // peer's lossless-active gate closes again, instead of being stuck open.
  const uint8_t oldRts = m_lldpRts;
  const uint8_t oldRtr = m_lldpRtr;
  m_lldpRts = m_lldpRemote.GetRvcWantBitmap ();
  m_lldpRtr = (uint8_t) (m_lldpRemote.GetSvcRtsBitmap () & m_lldpWant);
  if (m_lldpRts != oldRts || m_lldpRtr != oldRtr)
    {
      SendLldpWithState ();   // progress (or regression) -> next handshake round
    }
  // VC becomes lossless-active when local RTS and the peer's RTR agree; wake
  // the egress path (frames may have queued behind the gate). A revocation
  // closes the gate again (act 1->0) — that VC's frames re-queue behind
  // CanSend (no BE channel, §12.32).
  bool wake = false;
  if (m_cbfc)
    {
      for (uint8_t v = 0; v < SueCbfcEngine::NVC; ++v)
        {
          const bool act = (m_lldpRts >> v & 1u) && m_lldpRemote.GetRvcRtr (v);
          if (act && !m_cbfc->GetVcLosslessActive (v))
            {
              m_cbfc->SetVcLosslessActive (v, true);
              wake = true;
            }
          else if (!act && m_cbfc->GetVcLosslessActive (v))
            {
              m_cbfc->SetVcLosslessActive (v, false);
            }
        }
    }
  if (wake) { DequeueAndTransmit (); }
}

void
SueNetDevice::ApplyLldpFallback ()
{
  if (m_lldpFirstRemoteApplied) { return; }
  NS_LOG_WARN ("LLDP: no peer TLV within the exchange window — proceeding with local config");
  m_lldpRemoteRcvd = true;
  // Self-negotiation fixpoint: each round the "peer" mirrors our last
  // re-sent frame (want -> rts -> rtr -> active). The assignment bitmaps
  // converge within 3 rounds; re-sent frames go out on the (peerless)
  // channel as harmless no-ops.
  m_lldpRemote = m_lldpLocal;
  for (uint32_t round = 0; round < 3; ++round)
    {
      const uint8_t r0 = m_lldpRts, r1 = m_lldpRtr;
      OnRemoteLldpTlv ();
      if (m_lldpRts == r0 && m_lldpRtr == r1) { break; }
      m_lldpRemote = m_lldpLocal;
    }
}

void
SueNetDevice::SetVcWant (uint8_t vc, bool on)
{
  if (vc >= SueCbfcEngine::NVC) { return; }
  if (on) { m_lldpWant |= (uint8_t) (1u << vc); }
  else { m_lldpWant &= (uint8_t) ~(1u << vc); }
  m_lldpLocal.SetRvcWant (vc, on);
  // R_VC_RTR follows the latest want immediately (§5.2.8.5: receiver drops
  // RTR once it stops wanting the VC), using the current S_VC_RTS.
  m_lldpRtr = (uint8_t) (m_lldpRts & m_lldpWant);
  if (m_lldpFirstRemoteApplied)
    {
      SendLldpWithState ();   // push the new want snapshot to the peer
    }
}

void
SueNetDevice::HandleCfUpdate (uint32_t vc, uint32_t rVcCf)
{
  if (m_cbfc) { m_cbfc->OnCfUpdate (vc, rVcCf); DequeueAndTransmit (); }
}

void
SueNetDevice::PrependLlrPreamble (Ptr<Packet> p, uint32_t seq, bool eligible)
{
  // UEC §5.1.1.1: every frame carries an 8B LLR preamble; eligible frames tag
  // seq in B1..B3, ineligible frames use the standard preamble (0x55 marker).
  SueLlrPreambleHeader pre;
  pre.SetEligible (eligible, seq);
  p->AddHeader (pre);
}

void
SueNetDevice::Receive (Ptr<Packet> p)
{
  NS_LOG_FUNCTION (this << p);
  m_rxTrace (p);
  // Minimal PCS model: while PCS_status is FALSE (link glitch, 闪断) the
  // physical layer cannot decode anything — drop every incoming frame (control
  // frames included) without LLR/FC/upcall processing. The peer's replay buffer
  // sees no ACK/NACK and grows; the local pcs_lost_status_timer (engine) forces
  // a FLUSH if the glitch outlasts pcs_lost_status_timer_max.
  if (!m_pcsStatus)
    {
      NS_LOG_LOGIC ("PCS_status FALSE: dropping frame (" << p->GetSize () << "B)");
      return;
    }
  // Control frame? (tag-based dispatch via SueCtlTag metadata; control frames
  // are LLR-ineligible, no preamble, bypass FC credit. PFC/CC_Update are real
  // Ethernet frames identified on the wire by EtherType/Opcode.)
  SueCtlTag ctlTag;
  if (p->PeekPacketTag (ctlTag))
    {
      // LLR-SP-22: control-frame loss model (lost ACK/NACK/INIT/INIT_ECHO —
      // UEC tolerance clauses: replay-timer fallback / init-timeout retry).
      // The frame is dropped BEFORE the engine sees it, exactly like an
      // on-wire CtlOS corruption.
      if (m_errModel && m_errModel->CheckCtlDrop ())
        {
          NS_LOG_LOGIC ("Receive: control frame type=" << (uint32_t) ctlTag.GetType ()
                         << " dropped by error model (CtlOS lost)");
          return;
        }
      HandleCtlFrame (p, ctlTag.GetType ());
      return;
    }
  if (m_llr)
    {
      // UEC §5.1.1.1: every data frame on an LLR link carries an 8B preamble
      // (eligible or ineligible). Strip it, then gate by eligibility + RX LLR
      // mode: only eligible frames are filtered by the RX LLR (UEC §5.1.7);
      // ineligible frames (peer TX in BEST_EFFORT / LLR_OFF) and frames
      // arriving with llr_mode_local OFF pass up unfiltered (no seq check).
      SueLlrPreambleHeader pre;
      p->RemoveHeader (pre);
      bool eligible = pre.IsEligible ();
      if (eligible && m_llr->GetModeLocal ())
        {
          uint32_t seq = pre.GetSeq ();
          int fcsStatus = 0;   // 0=GOOD,1=POISONED,2=BAD
          SueFrameBadTag fbTag;
          if (p->PeekPacketTag (fbTag))
            {
              fcsStatus = 1;   // TX-poisoned by the peer -> POISONED (§5.1.10)
            }
          else if (m_errModel)
            {
              SueErrorModel::FcsStatus st = m_errModel->CheckFcs (p);
              fcsStatus = (st == SueErrorModel::GOOD) ? 0 : (st == SueErrorModel::POISONED) ? 1 : 2;
            }
          SueLlrEngine::RxResult res = m_llr->RxFrame (seq, fcsStatus);
          if (res == SueLlrEngine::DROP)
            {
              // §5.2.9 rule 2: LLR-dropped frame does NOT update R_VC_CC
              // (structural — we return before OnRx/OnDrain; no window toggle
              // needed, the engine drives the window via SetLlrWindowCb).
              return;
            }
          if (res == SueLlrEngine::ACCEPT_POISONED)
            {
              // §5.1.10 frame_bad reporting: mark so the upper layer can detect
              // (TX-poisoned frames already carry the tag from the sender).
              SueFrameBadTag fb;
              if (!p->PeekPacketTag (fb)) { p->AddPacketTag (fb); }
            }
          // ACCEPT or ACCEPT_POISONED: pass up
        }
    }
  else if (m_llrEnabled)
    {
      // Legacy fallback (engine absent, llr_enabled flag set): strip preamble,
      // drop BAD frames only.
      SueLlrPreambleHeader pre;
      p->RemoveHeader (pre);
      int fcsStatus = 0;   // 0=GOOD,1=POISONED,2=BAD
      SueFrameBadTag fbTag;
      if (p->PeekPacketTag (fbTag)) { fcsStatus = 1; }
      else if (m_errModel)
        {
          SueErrorModel::FcsStatus st = m_errModel->CheckFcs (p);
          fcsStatus = (st == SueErrorModel::GOOD) ? 0 : (st == SueErrorModel::POISONED) ? 1 : 2;
        }
      if (fcsStatus == 2) { return; }   // simple: drop BAD only
    }
  SueHeader h;
  p->PeekHeader (h);
  // Only the two configured SUE EtherTypes are valid on the data path; anything
  // else (e.g. an injected IP / 802.1Qbb frame) would be silently mis-parsed as
  // a no-shim SUE frame and forwarded. Control frames are dispatched by tag
  // earlier, so their real EtherTypes never reach this check.
  if (h.GetEtherType () != SueConfig::EthType0 () && h.GetEtherType () != SueConfig::EthType1 ())
    {
      NS_LOG_LOGIC ("Receive: non-SUE EtherType 0x" << std::hex << h.GetEtherType ()
                     << " on data path, drop");
      return;
    }
  uint8_t vc = ComputeVc (h);
  // Flow control ingress: via the facade if set, else the legacy per-engine
  // path (byte-identical to the pre-facade wiring).
  if (m_fc) { m_fc->OnRx (vc, p->GetSize ()); }
  else
    {
      if (m_cbfc) { m_cbfc->OnRx (vc, p->GetSize ()); }
      if (m_pfc) { m_pfc->OnRx (vc, p->GetSize ()); m_pfc->CheckThresholds (); }
    }
  // Drain (credit refund / threshold re-check) is unified: OnDrain dispatches
  // internally (facade / CBFC / legacy PFC via OnDrainPfc). Under the CBFC
  // backpressure deferral (§12.30) the switch port charges R_VC_CC but holds
  // the refund until the switch node admits the frame onto an egress port
  // (RefundCredit) — the credit consumed therefore tracks egress congestion
  // and the CF_Update the sender sees carries the real 2:1 backpressure.
  if ((m_fc || m_cbfc || m_pfc) && m_drainDelay > Seconds (0) && !m_deferCreditRefund)
    { ScheduleSelf (m_drainDelay, &SueNetDevice::OnDrain, this, vc, p->GetSize ()); }
  else if ((m_fc || m_cbfc || m_pfc) && !m_deferCreditRefund)
    { OnDrain (vc, p->GetSize ()); }
  // Note: with CF_min/CF_max timers enabled (SetCfUpdateTimers), OnDrain
  // routes through OnCfDirty instead of emitting per-frame here.
  if (!m_upcall.IsNull ()) { m_upcall (this, p, h); }
}

void
SueNetDevice::OnDrain (uint32_t vc, uint32_t bytes)
{
  if (m_fc) { m_fc->OnDrain (vc, bytes); }
  else if (m_cbfc) { m_cbfc->OnDrain (vc, bytes); }
  else if (m_pfc) { OnDrainPfc (vc, bytes); return; }   // PFC has no CF_Update
  // CBFC (facade or legacy): refund the receiver credit via CF_Update.
  // UEC §5.2.6.1 gating: when the CF_min/CF_max timers are configured, the
  // drain only marks the VC dirty and the generation is driven by the two
  // triggers (dirty + CF_min elapsed, or the periodic CF_max full update) —
  // not one CF_Update per drained frame. Otherwise keep the legacy per-frame
  // sink call (tests / non-config device defaults).
  // Either timer enables the batched path: CF_min-only configs (CF_max=0) must
  // still route drains through OnCfDirty -> trigger 1 (dirty VC one-shot);
  // previously the gate checked CF_max only, so a CF_min-only config silently
  // fell back to per-frame legacy emission.
  if (m_cfMaxInterval > Seconds (0) || m_cfMinInterval > Seconds (0)
      || m_cfThresholdBytes > 0)
    {
      OnCfDirty (vc);
      if (m_cfThresholdBytes > 0)
        {
          // SDK credit_threshold 语义:按收到的数据字节计。阈值到点即请求
          // 上报;CF_min>0 时由地板网格统一排队(与芯片 spacing 地板同构),
          // CF_min=0 时立即批量发送(data-proportional,端口速率无关)。
          // 单次 drain 可能跨过多个阈值量子(帧长 ≥ 阈值,如 4096B 帧 vs
          // 2075B 阈值):按 floor(累计字节/阈值) 逐量子各发一条,余量结转;
          // dirty 在循环外清零(量子间内容相同,循环内清零会把后续量子
          // 吞掉,速率塌到帧率而非字节率/阈值)。无穿越时 dirty 保留,
          // 由下一次穿越或 CF_max 全量兜底发送。
          m_cfAccumBytes += bytes;
          bool quantaSent = false;
          while (m_cfAccumBytes >= m_cfThresholdBytes)
            {
              m_cfAccumBytes -= m_cfThresholdBytes;
              if (m_cfMinInterval == Seconds (0) && m_cfDirtyMask != 0)
                {
                  SendCfUpdateBatch (m_cfDirtyMask);
                  quantaSent = true;
                  m_lastCfUpdate = Simulator::Now ();
                }
            }
          if (quantaSent) { m_cfDirtyMask = 0; }
        }
    }
  else if (!m_cfSink.IsNull ())
    { m_cfSink (vc, m_fc ? m_fc->GetRvcCf (vc) : m_cbfc->GetRvcCf (vc)); }
}

void
SueNetDevice::OnDrainPfc (uint32_t vc, uint32_t bytes)
{
  if (!m_pfc) { return; }
  m_pfc->OnDrain (vc, bytes);
  m_pfc->CheckThresholds ();   // may trigger resume
}

